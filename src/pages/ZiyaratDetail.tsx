// 3. المكون الرئيسي
// -------------------------------------------------------------
export function ZiyaratDetail() {
  const { id } = useParams<{ id: string }>();
  const navigate = useNavigate();

  const getValidKey = (paramId?: string): string => {
    if (!paramId) return "warith";
    const cleanId = paramId.toString().toLowerCase().trim();
    if (ZIYARAT_DATA[cleanId]) return cleanId;
    
    const numericMap: Record<string, string> = {
      "1": "ashura",
      "2": "warith",
      "3": "aminullah",
      "4": "jamia",
      "5": "aleyasin",
      "6": "nahiya",
      "7": "arbaeen",
      "8": "saturday",
      "9": "sunday",
      "10": "monday",
      "11": "tuesday",
      "12": "wednesday",
      "13": "thursday",
      "14": "friday"
    };
    return numericMap[cleanId] || "warith";
  };

  const currentKey = getValidKey(id);
  const currentItem = ZIYARAT_DATA[currentKey] || ZIYARAT_DATA["warith"];
  const currentIndex = ZIYARAT_KEYS.indexOf(currentKey);

  // حالات التحكم
  const [isPlaying, setIsPlaying] = useState<boolean>(false);
  const [isMuted, setIsMuted] = useState<boolean>(false);
  const [isDownloaded, setIsDownloaded] = useState<boolean>(false);
  const [isDownloading, setIsDownloading] = useState<boolean>(false);
  const [fontSize, setFontSize] = useState<number>(20);
  const [copied, setCopied] = useState<boolean>(false);

  const audioRef = useRef<HTMLAudioElement | null>(null);
  const scrollContainerRef = useRef<HTMLDivElement | null>(null);

  useEffect(() => {
    setIsPlaying(false);
    checkOfflineStatus();
    
    // إعادة التمرير لأعلى عند تغيير الزيارة
    if (scrollContainerRef.current) {
      scrollContainerRef.current.scrollTop = 0;
    }
  }, [id, currentKey]);

  const checkOfflineStatus = async () => {
    if (!currentItem) return;
    const localBlob = await getOfflineAudio(currentItem.id);
    if (localBlob && audioRef.current) {
      audioRef.current.src = URL.createObjectURL(localBlob);
      setIsDownloaded(true);
    } else if (audioRef.current) {
      audioRef.current.src = currentItem.audioUrl;
      setIsDownloaded(false);
    }
  };

  const goToNextZiyarat = () => {
    if (currentIndex < ZIYARAT_KEYS.length - 1) {
      navigate(`/ziyarat/${ZIYARAT_KEYS[currentIndex + 1]}`);
    }
  };

  const goToPrevZiyarat = () => {
    if (currentIndex > 0) {
      navigate(`/ziyarat/${ZIYARAT_KEYS[currentIndex - 1]}`);
    }
  };

  const seekAudio = (seconds: number) => {
    if (audioRef.current) {
      audioRef.current.currentTime += seconds;
    }
  };

  const toggleMute = () => {
    if (audioRef.current) {
      audioRef.current.muted = !isMuted;
      setIsMuted(!isMuted);
    }
  };

  const handleCopyText = () => {
    navigator.clipboard.writeText(currentItem.text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const zoomInText = () => setFontSize(prev => Math.min(prev + 2, 36));
  const zoomOutText = () => setFontSize(prev => Math.max(prev - 2, 14));

  const handleDownloadOffline = async () => {
    if (isDownloaded) {
      alert("✅ الصوت محفوظ أوفلاين وتعمل هذه الشاشة بدون إنترنت!");
      return;
    }
    setIsDownloading(true);
    try {
      const response = await fetch(encodeURI(currentItem.audioUrl));
      if (!response.ok) throw new Error("تعذر جلب الملف");
      const blob = await response.blob();
      await saveAudioOffline(currentItem.id, blob);
      if (audioRef.current) {
        audioRef.current.src = URL.createObjectURL(blob);
      }
      setIsDownloaded(true);
      alert("🎉 تم حفظ الصوت بنجاح لاستخدامه أوفلاين!");
    } catch {
      alert("❌ تعذر التحميل. تأكد من الاتصال بالإنترنت أولاً.");
    } finally {
      setIsDownloading(false);
    }
  };

  const togglePlayAudio = () => {
    if (!audioRef.current) return;
    if (isPlaying) {
      audioRef.current.pause();
      setIsPlaying(false);
    } else {
      audioRef.current.play().then(() => {
        setIsPlaying(true);
      }).catch(() => {
        alert("تعذر تشغيل الصوت. أعد التحميل أو تحقق من الاتصال.");
      });
    }
  };

  return (
    <div className="h-screen bg-[#022c22] text-[#f0f9ff] flex flex-col p-4 select-none overflow-hidden" dir="rtl">
      <audio ref={audioRef} onEnded={() => setIsPlaying(false)} preload="metadata" />

      {/* 1. الهيدر وفضل الزيارة - ثابت في الأعلى */}
      <div className="shrink-0 mb-2">
        <div className="flex items-center justify-between mb-2">
          <button 
            onClick={() => navigate(-1)} 
            className="p-2 bg-[#064e3b] text-[#fbbf24] rounded-full border border-[#059669]/30 hover:bg-[#047857] transition"
          >
            <ArrowRight size={20} />
          </button>
          
          <h2 className="text-xl font-bold text-[#fbbf24]">{currentItem.title}</h2>
          
          <div className="flex items-center gap-1.5 bg-[#064e3b]/50 p-1 rounded-xl border border-[#059669]/30">
            <button onClick={zoomInText} className="p-1.5 text-[#fbbf24] hover:bg-[#022c22] rounded-lg transition" title="تكبير الخط">
              <ZoomIn size={16} />
            </button>
            <button onClick={zoomOutText} className="p-1.5 text-[#fbbf24] hover:bg-[#022c22] rounded-lg transition" title="تصغير الخط">
              <ZoomOut size={16} />
            </button>
            <button onClick={handleCopyText} className="p-1.5 text-[#fbbf24] hover:bg-[#022c22] rounded-lg transition" title="نسخ النص">
              {copied ? <Check size={16} className="text-green-400" /> : <Copy size={16} />}
            </button>
          </div>
        </div>

        {currentItem.benefits && (
          <div className="p-2.5 bg-[#064e3b]/40 border border-[#059669]/30 rounded-2xl text-center text-xs text-[#34d399] leading-relaxed">
            {currentItem.benefits}
          </div>
        )}
      </div>

      {/* 2. شاشة عرض النص - مرنة ومجهزة بالتمرير بدون حدود ملغية */}
      <div 
        ref={scrollContainerRef}
        className="flex-1 overflow-y-auto bg-[#03382c] border border-[#059669]/30 rounded-3xl p-5 my-2 shadow-inner relative leading-relaxed scrollbar-thin scrollbar-thumb-[#059669] scrollbar-track-transparent"
      >
        <AnimatePresence mode="wait">
          <motion.div
            key={currentKey}
            initial={{ opacity: 0, y: 10 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: -10 }}
            transition={{ duration: 0.2 }}
            className="w-full flex flex-col items-center justify-start min-h-full py-2"
          >
            <p 
              style={{ fontSize: `${fontSize}px`, lineHeight: `${Math.max(fontSize * 2.1, 40)}px` }} 
              className="text-center font-serif text-[#f0f9ff] tracking-wide w-full overflow-visible whitespace-pre-line"
            >
              {currentItem.text}
            </p>
          </motion.div>
        </AnimatePresence>
      </div>

      {/* 3. شريط التنقل بين الزيارات - ثابت */}
      <div className="shrink-0 flex items-center justify-between bg-[#064e3b]/60 border border-[#059669]/30 rounded-2xl p-2 mb-2">
        <button 
          onClick={goToNextZiyarat}
          disabled={currentIndex >= ZIYARAT_KEYS.length - 1}
          className={`flex items-center gap-1 px-3 py-1.5 rounded-xl font-bold text-xs transition ${
            currentIndex >= ZIYARAT_KEYS.length - 1 
              ? 'opacity-30 text-gray-400 cursor-not-allowed' 
              : 'text-[#fbbf24] bg-[#022c22]/60 hover:bg-[#022c22]'
          }`}
        >
          الزيارة التالية <ChevronLeft size={16} />
        </button>

        <div className="px-3 py-1 bg-[#022c22] border border-[#059669]/40 rounded-xl text-xs font-bold text-[#fbbf24]">
          {currentIndex + 1} / {ZIYARAT_KEYS.length}
        </div>

        <button 
          onClick={goToPrevZiyarat}
          disabled={currentIndex <= 0}
          className={`flex items-center gap-1 px-3 py-1.5 rounded-xl font-bold text-xs transition ${
            currentIndex <= 0 
              ? 'opacity-30 text-gray-400 cursor-not-allowed' 
              : 'text-[#fbbf24] bg-[#022c22]/60 hover:bg-[#022c22]'
          }`}
        >
          <ChevronRight size={16} /> الزيارة السابقة
        </button>
      </div>

      {/* 4. المشغل الصوتي - ثابت بالأسفل */}
      <div className="shrink-0 bg-[#064e3b]/90 border border-[#059669]/40 rounded-3xl p-2 flex items-center justify-between gap-2 overflow-hidden">
        <div className="flex items-center gap-1 shrink-0">
          <button 
            onClick={togglePlayAudio}
            className="w-10 h-10 bg-[#fbbf24] text-[#022c22] rounded-full flex items-center justify-center shadow-lg active:scale-95 transition"
          >
            {isPlaying ? <Pause size={20} fill="#022c22" /> : <Play size={20} fill="#022c22" className="mr-0.5" />}
          </button>
          
          <button onClick={() => seekAudio(-10)} className="p-1.5 text-[#059669] hover:text-[#fbbf24] transition" title="-10 ثوانٍ">
            <Rewind size={16} />
          </button>

          <button onClick={() => seekAudio(10)} className="p-1.5 text-[#059669] hover:text-[#fbbf24] transition" title="+10 ثوانٍ">
            <FastForward size={16} />
          </button>

          <button 
            onClick={() => { if (audioRef.current) audioRef.current.currentTime = 0; }} 
            className="p-1.5 text-[#059669] hover:text-[#fbbf24] transition" 
            title="إعادة"
          >
            <RotateCcw size={15} />
          </button>

          <button 
            onClick={handleDownloadOffline} 
            className={`p-1.5 transition ${isDownloaded ? 'text-[#34d399]' : 'text-[#059669] hover:text-[#fbbf24]'}`}
          >
            {isDownloading ? <Loader2 size={16} className="animate-spin" /> : isDownloaded ? <CheckCircle2 size={16} /> : <Download size={16} />}
          </button>
        </div>

        <div className="flex-1 min-w-0 text-center px-1">
          <h4 className="font-bold text-xs text-[#f0f9ff] truncate">{currentItem.title}</h4>
          <p className="text-[10px] text-[#059669] truncate">
            {isPlaying ? (isMuted ? "مكتوم..." : "جاري التشغيل...") : isDownloaded ? "جاهز أوفلاين" : "متوقف"}
          </p>
        </div>

        <button 
          onClick={toggleMute}
          className={`p-2 rounded-xl border transition shrink-0 ${
            isMuted 
              ? 'bg-red-500/20 border-red-500/50 text-red-400' 
              : 'bg-[#022c22]/60 border-[#059669]/40 text-[#34d399] hover:text-[#fbbf24]'
          }`}
          title={isMuted ? "إلغاء الكتم" : "كتم الصوت"}
        >
          {isMuted ? <VolumeX size={18} /> : <Volume2 size={18} />}
        </button>
      </div>
    </div>
  );
}
